const assert=require('node:assert/strict');const {validate}=require('../src/schematic-validation.js');
const base={symbols:[{id:'a',type:'LS',x:10,y:20},{id:'b',type:'LAMP',x:30,y:20}],wires:[{a:'a',b:'b'}]};
assert.equal(validate(base).valid,true);assert.match(validate(base).warnings.join(' '),/Klemmenzuordnung unvollständig/);
assert.equal(validate({...base,wires:[{a:'a',b:'missing'}]}).valid,false);
assert.equal(validate({...base,wires:[{a:'a',b:'a'}]}).valid,false);
assert.equal(validate({...base,symbols:[base.symbols[0],base.symbols[0]]}).valid,false);
assert.equal(validate({...base,wires:[]}).warnings.length,2);
assert.ok(validate({...base,wires:[{a:'a',b:'b'},{a:'b',b:'a'}]}).warnings.some(w=>w.includes('doppelte Verbindung')));
assert.equal(validate({...base,symbols:[{id:'x',type:'INVALID',x:0,y:0}]}).valid,false);
assert.equal(validate({}).valid,false);
const assigned={symbols:[{...base.symbols[0],manualTerminals:['1']},{...base.symbols[1],manualTerminals:['2']}],wires:[{a:'a',b:'b',fromTerminal:'1',toTerminal:'2'}]};
assert.equal(validate(assigned).valid,true);
assert.equal(validate(assigned).warnings.length,0);
assert.equal(validate({...assigned,wires:[{a:'a',b:'b',fromTerminal:'X',toTerminal:'2'}]}).valid,false);
assert.match(validate({...assigned,wires:[{a:'a',b:'b',fromTerminal:'X',toTerminal:'2'}]}).errors.join(' '),/Startklemme/);
const multi={symbols:[{...base.symbols[0],manualTerminals:['1','3']},{...base.symbols[1],manualTerminals:['2','4']}],wires:[{a:'a',b:'b',fromTerminal:'1',toTerminal:'2'},{a:'a',b:'b',fromTerminal:'3',toTerminal:'4'}]};
assert.equal(validate(multi).valid,true);
assert.equal(validate(multi).warnings.length,0,'Distinct terminal pairs must not be mistaken for duplicate wires');
assert.ok(validate({...multi,wires:[multi.wires[0],{a:'b',b:'a',fromTerminal:'2',toTerminal:'1'}]}).warnings.some(w=>w.includes('doppelte Verbindung')),'Reversed same-terminal wire should be detected as duplicate');
console.log('Schematic structural and manual-terminal validation checks passed');
