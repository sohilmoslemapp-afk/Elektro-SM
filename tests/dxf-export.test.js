'use strict';
const assert=require('node:assert/strict');
const {exportDxf}=require('../src/dxf-export');
const p={symbols:[{id:'S1',type:'LS',x:100,y:200},{id:'S2',type:'MOTOR',x:300,y:200}],wires:[{a:'S1',b:'S2'}]};
const d=exportDxf(p);
assert.match(d,/\$ACADVER\n1\nAC1009/);
assert.equal((d.match(/\nCIRCLE\n/g)||[]).length,2);
assert.equal((d.match(/\nLINE\n/g)||[]).length,1);
assert.match(d,/\nWIRES\n/);
assert.match(d,/\nEOF\n$/);
assert.throws(()=>exportDxf({symbols:[],wires:[{a:'x',b:'y'}]}),/endpoint/);
assert.throws(()=>exportDxf({symbols:[{id:'bad',x:Infinity,y:0}],wires:[]}),/Invalid symbol/);
const sanitized=exportDxf({symbols:[{id:'A\n0\nLINE',type:'LS',x:0,y:0}],wires:[]});
assert(!sanitized.includes('A\n0\nLINE'));
const withTerminals=exportDxf({symbols:[{id:'A',type:'LS',x:100,y:200,manualTerminals:['1','2']},{id:'B',type:'MOTOR',x:300,y:200,manualTerminals:['U1','V1']}],wires:[{a:'A',b:'B',fromTerminal:'2',toTerminal:'U1'}]});
assert.equal((withTerminals.match(/\nTERMINALS\n/g)||[]).length,4);
assert.equal((withTerminals.match(/\nTERMINAL_LABELS\n/g)||[]).length,4);
assert.match(withTerminals,/\n1\nU1\n/);
assert.match(withTerminals,/\n10\n143\n20\n-183\n30\n0\n11\n257\n21\n-183\n31\n0/);
assert.throws(()=>exportDxf({symbols:[{id:'A',x:100,y:200},{id:'B',x:300,y:200}],wires:[{a:'A',b:'B',fromTerminal:'9'}]}),/Terminal position/);
console.log('DXF R12 geometry and explicit terminal coordinate export tests passed');
