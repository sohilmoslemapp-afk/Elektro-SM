'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../prototypes/ElektroPlan-SM-integriert.html'),'utf8');
const validation=require('../src/schematic-validation.js');
const start=html.indexOf('function validateDiagram()');
const end=html.indexOf("$('checkDiagram').onclick=validateDiagram",start);
assert.ok(start>=0&&end>start,'integrated diagram validation exists');
assert.match(html.slice(start,end),/ElektroPlanValidation\.validate\(data\)/);
const symbols=['a|b','c','a','b|c'].map((id,i)=>({id,type:'SW',x:100+i*40,y:100,manualTerminals:['1']}));
const result=validation.validate({symbols,wires:[{a:'a|b',b:'c',fromTerminal:'1',toTerminal:'1'},{a:'a',b:'b|c',fromTerminal:'1',toTerminal:'1'},{a:'c',b:'a|b',fromTerminal:'1',toTerminal:'1'}]});
assert.equal(result.valid,true);
assert.equal(result.warnings.filter(w=>w.includes('doppelte Verbindung')).length,1,'only reversed duplicate must warn');
assert.match(fs.readFileSync(path.join(__dirname,'../src/schematic-validation.js'),'utf8'),/JSON\.stringify\(\[\[w\.a,w\.fromTerminal\],\[w\.b,w\.toTerminal\]\]/);
console.log('Integrated diagram delegates collision-safe duplicate wire detection to core validator');
