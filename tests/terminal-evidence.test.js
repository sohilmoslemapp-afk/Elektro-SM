const assert=require('node:assert/strict');
const evidence=require('../src/terminal-evidence.js');
const templates=require('../src/device-templates.js');
const editor=require('../src/schematic-editor.js');
assert.equal(evidence.validate({status:'generic-unverified'}).valid,true);
assert.equal(evidence.validate({status:'manufacturer-documented'}).valid,false);
assert.equal(evidence.safeUrl('javascript:alert(1)'),false);
assert.equal(evidence.safeUrl('http://example.com'),false);
assert.equal(evidence.safeUrl('https://user:pass@example.com'),false);
assert.equal(evidence.safeUrl('https://example.com/document.pdf'),true);
const metadata={status:'manufacturer-documented',manufacturer:'Example',model:'Sample',documentTitle:'Manufacturer data sheet',documentUrl:'https://example.com/document.pdf'};
assert.equal(evidence.validate(metadata).valid,true);
const device=templates.instantiate('mcb-1p','Q1',10,20);
assert.equal(editor.valid({version:1,symbols:[device],wires:[]}),true);
const documented=evidence.apply(device,metadata);
assert.equal(editor.valid({version:1,symbols:[documented],wires:[]}),true);
assert.equal(editor.valid({version:1,symbols:[{...device,terminalEvidence:{status:'invalid'}}],wires:[]}),false);
assert.equal(editor.valid({version:1,symbols:[{...device,terminalEvidence:{status:'generic-unverified',documentUrl:'javascript:bad'}}],wires:[]}),false);
console.log('Terminal evidence tests passed');
