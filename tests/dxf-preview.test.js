'use strict';
const assert=require('node:assert/strict');
const {exportDxf}=require('../src/dxf-export');
const {previewDxf}=require('../src/dxf-preview');
const dxf=exportDxf({symbols:[{id:'A',type:'LS',x:100,y:200,manualTerminals:['1','2']},{id:'B',type:'MOTOR',x:300,y:200}],wires:[{a:'A',b:'B'}]});
const p=previewDxf(dxf);
assert.equal(p.entities.filter(e=>e.type==='LINE').length,1);
assert.equal(p.entities.filter(e=>e.type==='CIRCLE').length,4);
assert(p.entities.some(e=>e.type==='TEXT'&&e.text.includes('MOTOR')));
assert.equal(p.unsupportedCount,0);
assert.throws(()=>previewDxf('0\nSECTION\n2\nENTITIES\n0\nLINE\n10\nInfinity\n0\nENDSEC\n'),/coordinate/);
assert.throws(()=>previewDxf('0\nSECTION\n2\nENTITIES\n0\nLINE\n10'),/Truncated/);
assert.throws(()=>previewDxf('x\nfoo\n'),/group code/);
const unsupported=previewDxf('0\nSECTION\n2\nENTITIES\n0\nARC\n8\nOTHER\n0\nSPLINE\n8\nOTHER\n0\nLINE\n8\nWIRES\n10\n1\n20\n2\n11\n3\n21\n4\n0\nENDSEC\n0\nEOF\n');
assert.equal(unsupported.entities.length,1,'supported line should remain visible');
assert.equal(unsupported.unsupportedCount,2,'unsupported geometry must be reported, not silently omitted');
assert.throws(()=>previewDxf('0\nSECTION\n2\nENTITIES\n0\nENDSEC\n'),/EOF/);
assert.throws(()=>previewDxf('0\nEOF\n'),/ENTITIES/);
assert.throws(()=>previewDxf('0\nSECTION\n2\nENTITIES\n0\nLINE\n10\n1\n20\n2\n11\n3\n21\n4\n0\nEOF\n'),/Incomplete/);
assert.throws(()=>previewDxf('0\nSECTION\n2\nENTITIES\n0\nSECTION\n2\nHEADER\n0\nENDSEC\n0\nEOF\n'),/Nested/);
assert.throws(()=>previewDxf('0\nENDSEC\n0\nEOF\n'),/Unexpected/);
assert.throws(()=>previewDxf('0\nSECTION\n2\nENTITIES\n0\nEOF\n'),/EOF before ENDSEC/);
console.log('Read-only DXF geometry preview and export roundtrip passed');
