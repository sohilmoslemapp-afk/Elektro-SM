const { chromium } = require('playwright');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('file://'+path.resolve(__dirname,'../prototypes/ElektroPlan-SM-integriert.html'));
    const layout=await page.evaluate(()=>({viewport:window.innerWidth,pageWidth:document.documentElement.scrollWidth,canvas:document.querySelector('#drawing').getBoundingClientRect().toJSON(),nav:document.querySelector('nav').getBoundingClientRect().toJSON()}));
    if(layout.pageWidth>layout.viewport+2)throw Error('Mobile horizontal overflow: '+JSON.stringify(layout));
    if(layout.canvas.width<250||layout.canvas.height<300)throw Error('Mobile drawing canvas too small');
    if(layout.nav.width<250)throw Error('Mobile navigation too narrow');
    await page.locator('[data-tab="features"]').click();
    if(!await page.locator('#features').isVisible())throw Error('German capabilities page did not open');
    if(await page.locator('#plan').isVisible())throw Error('Plan must hide while capabilities page is active');
    if(!await page.locator('#features').getByText('Automatische Erkennung elektrischer Bauteile aus Fotos').isVisible())throw Error('Planned recognition disclosure missing');
    if(!await page.locator('#features').getByText('Firmenkonten, Lizenzen und zeitlich begrenzte Testzugänge').isVisible())throw Error('Planned licensing disclosure missing');
    await page.locator('[data-tab="plan"]').click();
    if(!await page.locator('#plan').isVisible()||await page.locator('#features').isVisible())throw Error('Navigation back to plan failed');
    await page.locator('[data-add="RCD"]').click();
    await page.locator('[data-add="LS"]').click();
    if(await page.locator('#symbols > g').count()!==2)throw Error('Adding symbols failed');
    await page.locator('#undoEdit').click();
    if(await page.locator('#symbols > g').count()!==1)throw Error('Undo failed');
    await page.locator('#redoEdit').click();
    if(await page.locator('#symbols > g').count()!==2)throw Error('Redo failed');
    const firstSymbol=page.locator('#symbols > g').first();
    const beforePosition=await firstSymbol.getAttribute('transform');
    const rect=await firstSymbol.boundingBox();
    if(!rect)throw Error('Symbol is not visible for drag');
    await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
    await page.mouse.down();
    await page.mouse.move(rect.x+rect.width/2+45,rect.y+rect.height/2+35,{steps:6});
    await page.mouse.up();
    const afterPosition=await page.locator('#symbols > g').first().getAttribute('transform');
    if(beforePosition===afterPosition)throw Error('Pointer drag did not move symbol');
    await page.locator('#wireMode').click();
    await page.locator('#symbols > g').nth(0).tap();
    await page.locator('#symbols > g').nth(1).tap();
    if(await page.locator('#wires > path').count()!==1)throw Error('Touch wiring failed');
    await page.locator('#showTerminalPicker').click();
    if(!await page.locator('#terminalPicker button').isDisabled())throw Error('Picker allowed saving without manually registered terminals');
    if(!await page.locator('#terminalPicker [role="status"]').textContent().then(t=>t.includes('zuerst Klemmen')))throw Error('Missing terminal guidance in picker');
    await page.locator('#showTerminalPicker').click();
    await page.locator('#checkPlan').click();
    if(!await page.locator('#planCheckResult').textContent().then(t=>t.includes('unvollständig')&&t.includes('Nicht zugeordnete schematische Leitungen: 1')))throw Error('Unassigned wire not marked incomplete');
    await page.locator('#symbols > g').nth(0).tap();
    await page.locator('#showTerminalEditor').click();
    if(!await page.locator('#terminalEditor p').textContent().then(t=>t.includes('Bauteil ')&&t.includes('keine Herstellerprüfung')))throw Error('Editor missing selected component identity and manual warning');
    await page.locator('#terminalEditor button').last().click();
    if(await page.locator('#terminalEditor').count())throw Error('Cancel did not close terminal editor');
    await page.locator('#showTerminalEditor').click();
    await page.locator('#terminalEditorInput').fill('ESC-CANCEL');
    await page.locator('#terminalEditorInput').press('Escape');
    if(await page.locator('#terminalEditor').count())throw Error('Escape failed to dismiss terminal editor');
    await page.locator('#showTerminalEditor').click();
    await page.locator('#terminalEditorInput').fill('STALE');
    await page.locator('#symbols > g').nth(1).tap();
    await page.locator('#terminalEditor button').first().click();
    if(!await page.locator('#message').textContent().then(t=>t.includes('Bauteilauswahl geändert')))throw Error('Stale terminal editor saved after selection changed');
    await page.locator('#symbols > g').nth(0).tap();
    await page.locator('#showTerminalEditor').click();
    await page.locator('#showTerminalEditor').click();
    await page.locator('#terminalEditorInput').fill('1, 2, A1');
    await page.locator('#terminalEditor button').first().click();
    if(!await page.locator('#symbols').textContent().then(t=>t.includes('Manuell: 1, 2, A1')))throw Error('Inline terminal editor did not save');
    await page.locator('#showTerminalEditor').click();
    await page.locator('#terminalEditorInput').fill('A1, A1');
    await page.locator('#terminalEditor button').first().click();
    if(!await page.locator('#message').textContent().then(t=>t.includes('Ungültige Klemmen')))throw Error('Inline editor accepted duplicate terminals');
    if(!await page.locator('#symbols').textContent().then(t=>t.includes('Manuell: 1, 2, A1')))throw Error('Invalid inline edit changed existing terminals');
    await page.locator('#showTerminalEditor').click();
    page.once('dialog',dialog=>dialog.accept('1, 2, A1'));
    await page.locator('#editManualTerminals').click();
    await page.locator('#symbols > g').nth(1).tap();
    page.once('dialog',dialog=>dialog.accept('3, 4, A2'));
    await page.locator('#editManualTerminals').click();
    let invalidTerminalAttempt=false;
    page.on('dialog',async dialog=>{
      if(dialog.message().includes('Leitung auswählen'))await dialog.accept('1');
      else if(dialog.message().includes('Klemme am ersten'))await dialog.accept(invalidTerminalAttempt?'UNKNOWN':'A1');
      else if(dialog.message().includes('Klemme am zweiten'))await dialog.accept('A2');
      else await dialog.dismiss();
    });
    await page.locator('#assignWireTerminals').click();
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Leitungsenden manuell zugeordnet'));
    if(!await page.locator('#wires').textContent().then(t=>t.includes('A1 → A2')))throw Error('Wire terminal assignment label missing');
    invalidTerminalAttempt=true;
    await page.locator('#assignWireTerminals').click();
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Klemmen müssen exakt'));
    if(!await page.locator('#wires').textContent().then(t=>t.includes('A1 → A2')))throw Error('Invalid terminal assignment overwrote existing wire');
    invalidTerminalAttempt=false;
    await page.locator('#showTerminalPicker').click();
    if(!await page.locator('#terminalPicker select').count().then(n=>n===3))throw Error('Mobile terminal picker dropdowns missing');
    const terminalOptions=await page.locator('#terminalPicker select').evaluateAll(selects=>selects.slice(1).map(select=>Array.from(select.options,o=>o.value)));
    if(JSON.stringify(terminalOptions)!==JSON.stringify([['1','2','A1'],['3','4','A2']]))throw Error('Terminal picker mixed up component terminals: '+JSON.stringify(terminalOptions));
    await page.locator('#terminalPicker select').nth(1).selectOption('1');
    await page.locator('#terminalPicker select').nth(2).selectOption('4');
    await page.locator('#terminalPicker button').click();
    if(!await page.locator('#wires').textContent().then(t=>t.includes('1 → 4')))throw Error('Dropdown did not apply selected terminal labels');
    await page.locator('#showTerminalPicker').click();
    if(await page.locator('#terminalPicker select').nth(1).inputValue()!=='1'||await page.locator('#terminalPicker select').nth(2).inputValue()!=='4')throw Error('Picker did not restore previously selected terminal labels');
    await page.locator('#terminalPicker select').nth(1).selectOption('A1');
    await page.locator('#terminalPicker select').nth(2).selectOption('A2');
    await page.locator('#terminalPicker button').click();
    if(!await page.locator('#wires').textContent().then(t=>t.includes('A1 → A2')))throw Error('Dropdown terminal assignment failed');
    await page.locator('#symbols > g').nth(0).tap();
    await page.locator('#showTerminalEditor').click();
    await page.locator('#terminalEditorInput').fill('1, 2');
    await page.locator('#terminalEditor button').first().click();
    if(!await page.locator('#message').textContent().then(t=>t.includes('Klemme wird von einer Leitung verwendet')))throw Error('Inline editor allowed deletion of connected terminal');
    if(!await page.locator('#wires').textContent().then(t=>t.includes('A1 → A2')))throw Error('Deleting connected terminal corrupted wire');
    await page.locator('#showTerminalEditor').click();
    await page.locator('#savePlan').click();
    await page.reload();
    if(!await page.locator('#wires').textContent().then(t=>t.includes('A1 → A2')))throw Error('Assigned wire terminals not restored after reload');
    if(!await page.locator('#symbols').textContent().then(t=>t.includes('Manuell: 1, 2, A1')&&t.includes('Manuell: 3, 4, A2')))throw Error('Manual terminals not restored after reload');
    await page.locator('#assignWireTerminals').click();
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Leitungsenden manuell zugeordnet'));
    if(!await page.locator('#wires').textContent().then(t=>t.includes('A1 → A2')))throw Error('Existing terminal wire assignment changed unexpectedly');
    await page.locator('#checkPlan').click();
    if(!await page.locator('#planCheckResult').isVisible())throw Error('Structural validation not displayed');
    if(!await page.locator('#planCheckResult').textContent().then(t=>t.includes('keine elektrische Freigabe')))throw Error('Electrical approval disclaimer missing');
    if(await page.locator('#planCheckResult').textContent().then(t=>t.includes('Nicht zugeordnete schematische Leitungen')))throw Error('Assigned wire still marked incomplete');
    await page.locator('[data-tab="camera"]').click();
    if(!await page.locator('#takePhoto').count() || !await page.locator('#choosePhoto').count())throw Error('Camera inputs missing');
    const tinyPng=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9M9S8AAAAASUVORK5CYII=','base64');
    await page.locator('#choosePhoto').setInputFiles({name:'oversized.png',mimeType:'image/png',buffer:Buffer.alloc(10*1024*1024+1)});
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('maximal 10 MB'));
    if(await page.locator('#preview').getAttribute('src'))throw Error('Oversized photo was previewed despite limit');
    await page.locator('#choosePhoto').setInputFiles({name:'not-an-image.txt',mimeType:'text/plain',buffer:Buffer.from('not an image')});
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Nur Bilddateien'));
    if(await page.locator('#preview').getAttribute('src'))throw Error('Non-image file was previewed');
    await page.locator('#choosePhoto').setInputFiles({name:'test-photo.png',mimeType:'image/png',buffer:tinyPng});
    await page.waitForFunction(()=>document.querySelector('#photoStatus').textContent.includes('test-photo.png'));
    if(!await page.locator('#preview').getAttribute('src').then(x=>x?.startsWith('data:image/png;base64,')))throw Error('Image preview missing');
    await page.reload();
    if(await page.locator('#preview').getAttribute('src'))throw Error('Photo unexpectedly persisted after reload');
    await page.locator('[data-tab="camera"]').click();
    await page.locator('#photoToParts').click();
    if(!await page.locator('#message').textContent().then(t=>t.includes('manuell eingeben')))throw Error('Empty photo identification fields not rejected');
    await page.locator('#photoBrand').fill('Test Hersteller');
    await page.locator('#photoModel').fill('TEST-123');
    await page.locator('#photoToParts').click();
    if(!await page.locator('#parts').isVisible())throw Error('Camera manual transfer did not open parts');
    if(await page.locator('#brand').inputValue()!=='Test Hersteller'||await page.locator('#model').inputValue()!=='TEST-123')throw Error('Camera manual metadata transfer failed');
    await page.locator('#type').selectOption({label:'Schütz'});
    await page.locator('#addPart').click();
    if(await page.locator('#partList li').count()!==1)throw Error('Transferred manual component was not saved');
    await page.locator('#partList li button').first().click();
    if(!await page.locator('#parts').isVisible())throw Error('Unsupported part should remain in library');
    if(await page.locator('#symbols > g').count()!==2)throw Error('Unsupported component type unexpectedly added a symbol');
    if(!await page.locator('#message').textContent().then(t=>t.includes('fehlt noch ein passendes Plansymbol')))throw Error('Unsupported symbol mapping warning missing');
    await page.locator('[data-tab="parts"]').click();
    await page.locator('#type').selectOption({label:'FI / RCD'});
    await page.locator('#addPart').click();
    await page.locator('#partList li').last().locator('button').first().click();
    if(await page.locator('#symbols > g').count()!==3)throw Error('RCD library-to-plan insertion failed');
    if(!await page.locator('#message').textContent().then(t=>t.includes('Dokument und Klemmen NICHT herstellerverifiziert')))throw Error('Unverified terminal warning missing');
    if(!await page.locator('#symbols > g').last().textContent().then(t=>t.includes('Test Hersteller TEST-123')))throw Error('Manual manufacturer/model label missing');
    await page.locator('#symbols > g').last().click();
    await page.locator('[data-tab="parts"]').click();
    await page.locator('#partList li').last().getByText('Daten auf ausgewähltes Symbol übernehmen').click();
    if(!await page.locator('#message').textContent().then(t=>t.includes('manuell übernommen')))throw Error('Apply-to-selected-symbol confirmation missing');
    if(await page.locator('#symbols > g').count()!==3)throw Error('Applying library data unexpectedly changed symbol count');
    await page.locator('[data-tab="parts"]').click();
    await page.locator('#partList li').last().getByText('Bibliothekseintrag löschen').click();
    if(await page.locator('#partList li').count()!==1)throw Error('Library deletion did not remove exactly one entry');
    await page.locator('[data-tab="plan"]').click();
    if(await page.locator('#symbols > g').count()!==3)throw Error('Library deletion damaged existing schematic symbols');
    await page.locator('#undoEdit').click();
    await page.locator('[data-tab="parts"]').click();
    if(await page.locator('#partList li').count()!==2)throw Error('Undo of library deletion did not restore entry');
    await page.locator('[data-tab="plan"]').click();
    await page.locator('#undoEdit').click();
    if(await page.locator('#symbols > g').count()!==2)throw Error('No-op metadata application should not add an undo step; symbol insertion undo failed');

    await page.locator('[data-tab="plan"]').click();
    await page.locator('#savePlan').click();
    await page.reload();
    if(await page.locator('#symbols > g').count()!==2)throw Error('Saved symbols not restored after reload');
    if(await page.locator('#wires > path').count()!==1)throw Error('Saved wire not restored after reload');
    const bomPromise=page.waitForEvent('download');
    await page.locator('#exportBom').click();
    const bomDownload=await bomPromise;
    const bomText=await require('node:fs/promises').readFile(await bomDownload.path(),'utf8');
    if(!bomText.includes('Hersteller (manuell)')||!bomText.includes('Modell (manuell)')||!bomText.includes('"Anzahl"'))throw Error('BOM CSV missing manufacturer/model/count columns');
    if(!bomText.includes('"Symbol-IDs"')||!bomText.includes('"Herstellerprüfung"')||!bomText.includes('NICHT herstellerverifiziert'))throw Error('BOM CSV lacks traceability or verification warning');
    const wireCsvPromise=page.waitForEvent('download');
    await page.locator('#exportWireList').click();
    const wireCsv=await wireCsvPromise;
    const wireCsvText=await require('node:fs/promises').readFile(await wireCsv.path(),'utf8');
    if(!wireCsvText.includes('Von Klemme (manuell)')||!wireCsvText.includes('Nach Klemme (manuell)'))throw Error('Wiring CSV omitted manual terminal headers');
    if(!wireCsvText.includes('"Leitung Nr."')||!wireCsvText.includes('"W1"'))throw Error('Wiring CSV missing numbered schematic wire reference');
    if(!await page.locator('#wires').textContent().then(t=>t.includes('W1')))throw Error('Schematic missing matching wire reference');
    if(!wireCsvText.includes('"A1"')||!wireCsvText.includes('"A2"')||!wireCsvText.includes('NICHT herstellerverifiziert'))throw Error('Wiring CSV omitted assigned terminal labels or safety warning');
    await page.locator('[data-tab="project"]').click();
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#exportJson').click();
    const projectDownload=await downloadPromise;
    if(projectDownload.suggestedFilename()!=='ElektroPlan-Projekt.json')throw Error('Project export filename incorrect');
    const fs = require('node:fs/promises');
    const exportedProject=await fs.readFile(await projectDownload.path());
    const exportedPayload=JSON.parse(exportedProject.toString('utf8'));
    if(exportedPayload.format!=='ElektroPlan-SM-1'||exportedPayload.data.symbols.length!==2||exportedPayload.data.wires.length!==1)throw Error('Exported project data incomplete');
    await page.locator('[data-tab="plan"]').click();
    await page.locator('[data-add="LAMP"]').click();
    if(await page.locator('#symbols > g').count()!==3)throw Error('Cannot prepare import restoration');
    await page.locator('[data-tab="project"]').click();
    await page.locator('#importJson').setInputFiles({name:'valid-project.json',mimeType:'application/json',buffer:exportedProject});
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Projekt importiert'));
    await page.locator('[data-tab="plan"]').click();
    if(await page.locator('#symbols > g').count()!==2||await page.locator('#wires > path').count()!==1)throw Error('Valid project import did not restore diagram');
    await page.locator('[data-tab="project"]').click();
    await page.locator('#importJson').setInputFiles({name:'invalid-project.json',mimeType:'application/json',buffer:Buffer.from('{"format":"invalid","data":{}}')});
    await page.waitForFunction(()=>document.querySelector('#message').textContent.includes('Import abgebrochen'));
    await page.locator('[data-tab="plan"]').click();
    if(await page.locator('#symbols > g').count()!==2 || await page.locator('#wires > path').count()!==1)throw Error('Invalid import damaged current project');
    if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
    console.log('Mobile Chromium smoke test passed: drag, add, undo, redo, tabs, camera image selection, save, reload, JSON export/import and invalid import protection');
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
