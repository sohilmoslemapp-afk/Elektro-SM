const { chromium } = require('playwright');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('file://'+path.resolve(__dirname,'../prototypes/ElektroPlan-SM-integriert.html'));
    await page.locator('[data-add="RCD"]').click();
    await page.locator('[data-add="LS"]').click();
    if(await page.locator('#symbols > g').count()!==2)throw Error('Adding symbols failed');
    await page.locator('#undoEdit').click();
    if(await page.locator('#symbols > g').count()!==1)throw Error('Undo failed');
    await page.locator('#redoEdit').click();
    if(await page.locator('#symbols > g').count()!==2)throw Error('Redo failed');
    const firstSymbol=page.locator('#symbols > g').first();
    const beforePosition=await firstSymbol.getAttribute('transform');
    const rect=await firstSymbol.boundingBox();
    if(!rect)throw Error('Symbol is not visible for drag');
    await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
    await page.mouse.down();
    await page.mouse.move(rect.x+rect.width/2+45,rect.y+rect.height/2+35,{steps:6});
    await page.mouse.up();
    const afterPosition=await page.locator('#symbols > g').first().getAttribute('transform');
    if(beforePosition===afterPosition)throw Error('Pointer drag did not move symbol');
    await page.locator('#wireMode').click();
    await page.locator('#symbols > g').nth(0).tap();
    await page.locator('#symbols > g').nth(1).tap();
    if(await page.locator('#wires > path').count()!==1)throw Error('Touch wiring failed');
    await page.locator('#checkPlan').click();
    if(!await page.locator('#planCheckResult').isVisible())throw Error('Structural validation not displayed');
    await page.locator('[data-tab="camera"]').click();
    if(!await page.locator('#takePhoto').count() || !await page.locator('#choosePhoto').count())throw Error('Camera inputs missing');
    const tinyPng=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9M9S8AAAAASUVORK5CYII=','base64');
    await page.locator('#choosePhoto').setInputFiles({name:'test-photo.png',mimeType:'image/png',buffer:tinyPng});
    await page.waitForFunction(()=>document.querySelector('#photoStatus').textContent.includes('test-photo.png'));
    if(!await page.locator('#preview').getAttribute('src').then(x=>x?.startsWith('data:image/png;base64,')))throw Error('Image preview missing');
    await page.locator('[data-tab="plan"]').click();
    await page.locator('#savePlan').click();
    await page.reload();
    if(await page.locator('#symbols > g').count()!==2)throw Error('Saved symbols not restored after reload');
    if(await page.locator('#wires > path').count()!==1)throw Error('Saved wire not restored after reload');
    if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
    console.log('Mobile Chromium smoke test passed: drag, add, undo, redo, tabs, camera image selection, save and reload');
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
